export function getSocialMediaPlatformById(id: string): SocialMediaPlatform | undefined {
  return socialMediaPlatforms.find((platform) => platform.id === id)
}

export function getSocialMediaServiceById(id: string): SocialMediaService | undefined {
  for (const platform of socialMediaPlatforms) {
    const service = platform.services.find((s) => s.id === id)
    if (service) return service
  }
  return undefined
}

export function getAllSocialMediaPlatforms(): SocialMediaPlatform[] {
  return socialMediaPlatforms
}

export function getAllSocialMediaServices(): SocialMediaService[] {
  const allServices: SocialMediaService[] = []
  for (const platform of socialMediaPlatforms) {
    allServices.push(...platform.services)
  }
  return allServices
}